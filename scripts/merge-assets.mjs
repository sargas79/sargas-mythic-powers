/**
 * Merges per-feature localization (lang/parts/*.json) into lang/en.json and per-feature styles
 * (styles/parts/*.css) into styles/mythic.css, so features can be developed in separate files.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

function deepMerge(target, source, path = "") {
  for (const [key, value] of Object.entries(source)) {
    const here = path ? `${path}.${key}` : key;
    if (value && typeof value === "object" && !Array.isArray(value)) {
      if (target[key] !== undefined && (typeof target[key] !== "object" || Array.isArray(target[key]))) {
        throw new Error(`lang key conflict at ${here}`);
      }
      target[key] ??= {};
      deepMerge(target[key], value, here);
    } else {
      if (target[key] !== undefined && target[key] !== value) throw new Error(`lang key conflict at ${here}`);
      target[key] = value;
    }
  }
  return target;
}

const langDir = join(root, "lang", "parts");
const merged = {};
for (const file of readdirSync(langDir)
  .filter((f) => f.endsWith(".json"))
  .sort()) {
  deepMerge(merged, JSON.parse(readFileSync(join(langDir, file), "utf8")));
}
writeFileSync(join(root, "lang", "en.json"), JSON.stringify(merged, null, 2) + "\n");

const styleDir = join(root, "styles", "parts");
const css = readdirSync(styleDir)
  .filter((f) => f.endsWith(".css"))
  .sort()
  .map((f) => `/* ---- ${f} ---- */\n${readFileSync(join(styleDir, f), "utf8").trim()}\n`)
  .join("\n");
writeFileSync(
  join(root, "styles", "mythic.css"),
  `/* Generated by scripts/merge-assets.mjs. Edit styles/parts/*.css. */\n\n${css}`,
);
console.log("merged lang and styles");
